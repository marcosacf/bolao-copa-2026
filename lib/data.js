export function atribuirTerceiros(tercList) {
  const qualif = tercList.filter(x => x.j > 0).sort((a, b) =>
    b.pts - a.pts || b.sg - a.sg || b.gp - a.gp || rankFifa(a.nome) - rankFifa(b.nome)
  ).slice(0, 8);
  let slots = {};

  if (qualif.length === 8) {
    const chave = qualif.map(x => x.grupo).slice().sort().join('');
    const mapping = FIFA_ANNEX_C[chave];
    if (mapping) {
      const pool = qualif.slice();
      let ok = true;
      mapping.forEach((letra, i) => {
        const idx = pool.findIndex(t => t.grupo === letra);
        if (idx !== -1) { slots['Q' + i] = pool[idx].nome; pool.splice(idx, 1); }
        else ok = false;
      });
      if (ok) return slots;
      slots = {};
    }
  }

  // Fallback: backtracking
  const assign = new Array(THIRD_SLOTS.length).fill(-1);
  const used = new Array(qualif.length).fill(false);
  function backtrack(slotIdx) {
    if (slotIdx === THIRD_SLOTS.length) return true;
    const cand = THIRD_SLOTS[slotIdx].cand;
    for (let t = 0; t < qualif.length; t++) {
      if (!used[t] && cand.indexOf(qualif[t].grupo) !== -1) {
        used[t] = true; assign[slotIdx] = t;
        if (backtrack(slotIdx + 1)) return true;
        used[t] = false; assign[slotIdx] = -1;
      }
    }
    return false;
  }
  backtrack(0);
  THIRD_SLOTS.forEach((slot, i) => {
    slots['Q' + i] = assign[i] !== -1 ? qualif[assign[i]].nome : '3º Classificado';
  });
  return slots;
}

export function calcularRankingTerceiros(oficiais) {
  const todos = [];
  let gruposCompletos = 0;
  const totalGrupos = Object.keys(GRUPOS).length;

  Object.keys(GRUPOS).forEach(letra => {
    const grupo = GRUPOS[letra];
    const jogosComResultado = grupo.jogos.filter((_, i) => oficiais[letra + '-' + i] !== undefined).length;
    if (jogosComResultado === 6) {
      gruposCompletos++;
      const s = calcStats(grupo, oficiais, letra);
      const sorted = Object.keys(s).map(k => ({ nome: k, pts: s[k].pts, sg: s[k].sg, gp: s[k].gp, j: s[k].j }))
        .sort((a, b) => b.pts - a.pts || b.sg - a.sg || b.gp - a.gp);
      const terceiro = sorted[2];
      todos.push({ grupo: letra, nome: terceiro.nome, pts: terceiro.pts, sg: terceiro.sg, gp: terceiro.gp, j: terceiro.j, pendente: false });
    } else {
      todos.push({ grupo: letra, nome: '—', pts: 0, sg: 0, gp: 0, j: 0, pendente: true });
    }
  });

  // Ordena: completos por pts/sg/gp/fifa; pendentes ao fim
  todos.sort((a, b) => {
    if (a.pendente !== b.pendente) return a.pendente ? 1 : -1;
    return b.pts - a.pts || b.sg - a.sg || b.gp - a.gp || rankFifa(a.nome) - rankFifa(b.nome);
  });

  // Top 8 não-pendentes => classificados
  let classifCount = 0;
  const entries = todos.map(e => {
    if (e.pendente) return Object.assign({}, e, { status: 'pendente' });
    if (classifCount < 8) { classifCount++; return Object.assign({}, e, { status: 'classificado' }); }
    return Object.assign({}, e, { status: 'eliminado' });
  });

  return { entries, gruposCompletos, totalGrupos };
}
